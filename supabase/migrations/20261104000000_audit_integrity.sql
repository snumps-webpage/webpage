-- Judge cross-document preconditions on the same locked rows as the write.
-- Existing migrations remain unchanged; flow names retain their contracts.
create or replace function flow_approve_study_request(p jsonb) returns jsonb
language plpgsql set search_path = public as $$
declare
  v_id       text := p ->> 'id';
  v_requests jsonb;
  v_req      jsonb;
  v_requester jsonb;
  v_studies  jsonb;
  v_touched  text[] := array['study-requests'];
begin
  perform app_require(p, array['id', 'studyId']);
  perform app_lock(array['members', 'studies', 'study-requests']);
  v_requests := app_rows('study-requests');
  v_req := app_find(v_requests, v_id);
  if v_req is null then raise exception 'NOT_FOUND'; end if;
  if v_req ->> 'status' <> 'pending' then raise exception 'CONFLICT'; end if;

  -- The same operating-roster rule as assertOrganizerCandidates: a missing
  -- or withdrawing requester cannot become the sole organizer of an open study.
  v_requester := app_find(app_rows('members'), v_req ->> 'requesterId');
  if v_requester is null or v_requester ->> 'status' = 'withdrawn' then
    raise exception 'VALIDATION_FAILED';
  end if;

  v_studies := app_rows('studies');
  if not exists (select 1 from jsonb_array_elements(v_studies) s
                  where s ->> 'sourceRequestId' = v_id) then
    perform app_put('studies', v_studies || jsonb_build_array(jsonb_build_object(
      'id', p ->> 'studyId',
      'title', v_req -> 'title',
      'semester', v_req -> 'semester',
      'textbook', v_req -> 'textbook',
      'description', v_req -> 'description',
      'note', '',
      'organizerIds', jsonb_build_array(v_req -> 'requesterId'),
      'participantIds', jsonb_build_array(v_req -> 'requesterId'),
      'pendingParticipantIds', '[]'::jsonb,
      'pendingTransfer', null,
      'schedule', '[]'::jsonb,
      'transferHistory', '[]'::jsonb,
      'photos', '[]'::jsonb,
      'status', 'recruiting',
      'sourceRequestId', v_id)));
    v_touched := v_touched || array['studies'];
  end if;

  perform app_put('study-requests', app_replace(v_requests, v_id,
    v_req || jsonb_build_object('status', 'approved')));
  return jsonb_build_object('touched', to_jsonb(v_touched), 'request', v_req);
end $$;

-- The activity's existence and copied fields cannot race its deletion/edit.
-- Each invocation still creates a new session, as the existing admin action did.
create or replace function flow_connect_activity(p jsonb) returns jsonb
language plpgsql set search_path = public as $$
declare
  v_activity jsonb;
  v_event jsonb;
begin
  perform app_require(p, array['activityId', 'eventId', 'pathId', 'attendCode']);
  perform app_lock(array['activities', 'events']);
  v_activity := app_find(app_rows('activities'), p ->> 'activityId');
  if v_activity is null then raise exception 'NOT_FOUND'; end if;

  v_event := jsonb_build_object(
    'id', p ->> 'eventId',
    'title', v_activity -> 'title',
    'date', v_activity -> 'date',
    'type', v_activity -> 'type',
    'status', 'active',
    'pathId', p ->> 'pathId',
    'attendCode', p ->> 'attendCode',
    'activityId', v_activity -> 'id',
    'applicantIds', '[]'::jsonb,
    'presenterIds', '[]'::jsonb,
    'studyId', null,
    'sessionNo', null,
    'autoGenerated', false,
    'sourceRequestId', null);
  perform app_put('events', app_rows('events') || jsonb_build_array(v_event));
  return jsonb_build_object('touched', jsonb_build_array('events'), 'event', v_event);
end $$;

create or replace function flow_set_activity_study(p jsonb) returns jsonb
language plpgsql set search_path = public as $$
declare
  v_id      text := p ->> 'activityId';
  v_study   text := p ->> 'studyId';
  v_acts    jsonb;
  v_act     jsonb;
  v_session text;
begin
  perform app_require(p, array['activityId']);
  if not p ? 'studyId' then
    raise exception 'VALIDATION_FAILED' using detail = 'missing-studyId';
  end if;
  perform app_lock(array['activities', 'events', 'studies']);
  v_acts := app_rows('activities');
  v_act := app_find(v_acts, v_id);
  if v_act is null then raise exception 'NOT_FOUND' using detail = 'activity'; end if;
  -- This used to be checked only on the caller's earlier activity read.
  if coalesce(v_act ->> 'type', '') not in ('스터디', '회식') then
    raise exception 'VALIDATION_FAILED' using detail = 'activity-type';
  end if;

  select e ->> 'studyId' into v_session
    from jsonb_array_elements(app_rows('events')) with ordinality as x(e, n)
   where e ->> 'activityId' = v_id
     and jsonb_typeof(e -> 'studyId') = 'string'
   order by n
   limit 1;
  if v_session is not null and v_study is distinct from v_session then
    raise exception 'VALIDATION_FAILED' using detail = 'session';
  end if;
  if (v_act ->> 'studyId') is not distinct from v_study then
    return jsonb_build_object('touched', '[]'::jsonb);
  end if;
  if v_study is not null and app_find(app_rows('studies'), v_study) is null then
    raise exception 'NOT_FOUND' using detail = 'study';
  end if;
  perform app_put('activities', app_replace(v_acts, v_id,
    v_act || jsonb_build_object('studyId', v_study)));
  return jsonb_build_object('touched', jsonb_build_array('activities'));
end $$;

do $$
declare f text;
begin
  foreach f in array array[
    'flow_approve_study_request(jsonb)',
    'flow_connect_activity(jsonb)',
    'flow_set_activity_study(jsonb)'
  ] loop
    execute format('revoke all on function %s from public', f);
    if exists(select 1 from pg_roles where rolname = 'anon') then
      execute format('revoke all on function %s from anon', f);
    end if;
    if exists(select 1 from pg_roles where rolname = 'authenticated') then
      execute format('revoke all on function %s from authenticated', f);
    end if;
    if exists(select 1 from pg_roles where rolname = 'service_role') then
      execute format('grant execute on function %s to service_role', f);
    end if;
  end loop;
end $$;
