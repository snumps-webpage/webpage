-- 20260928000000_atomic_flows.sql — multi-document flows as plpgsql functions
--
-- Design : docs/spec/ATOMIC-FLOWS.md (decision 2026-09-27, option B)
-- Run on : BOTH prod and dev, BEFORE deploying code that calls these
--          functions. Expand-only: the currently deployed code ignores them.
--          Idempotent — safe to re-run.
-- Also   : applied in-process by PGlite for tests and DATA_BACKEND=memory
--          (src/lib/server/data/store-memory.ts), so every statement must run
--          on plain Postgres without Supabase roles.
--
-- Conventions
--   * Every flow is `flow_<name>(p jsonb) returns jsonb`; PostgREST calls it as
--     rpc('flow_<name>', { p: {...} }).
--   * Failures RAISE a bare app error code as the message (NOT_FOUND, CONFLICT,
--     VALIDATION_FAILED, EVENT_NOT_OPEN, FORBIDDEN); the whole transaction
--     rolls back. The TS side maps the message to AppError.
--   * ids and timestamps come IN as arguments (generated by TS: ULID, KST ISO)
--     so SQL-written rows have exactly the shapes TS writes.
--   * Returns { "touched": [table names...], ... } — TS invalidates caches of
--     the touched tables.
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 1. Document helpers
-- ---------------------------------------------------------------------------

-- rows[] of a table document ('[]' when the document does not exist yet)
create or replace function app_rows(p_name text) returns jsonb
language sql stable set search_path = public as $$
  select coalesce(
    (select doc -> 'rows' from app_tables where name = p_name),
    '[]'::jsonb)
$$;

-- Lock table documents for the rest of the transaction, in name order (no
-- deadlocks between flows). Missing documents are created empty first so
-- they can be locked too — readers treat "missing" and "empty" alike.
create or replace function app_lock(p_names text[]) returns void
language plpgsql set search_path = public as $$
begin
  insert into app_tables (name, version, doc)
    select n, 1, jsonb_build_object('schemaVersion', 1, 'rows', '[]'::jsonb)
    from unnest(p_names) as n
    on conflict (name) do nothing;
  perform 1 from app_tables where name = any (p_names) order by name for update;
end $$;

-- Replace a (locked) table document's rows and bump its version — the same
-- version CAS the TS writers use, so a concurrent TS mutate retries.
create or replace function app_put(p_name text, p_rows jsonb) returns void
language plpgsql set search_path = public as $$
begin
  update app_tables
     set doc = jsonb_set(doc, '{rows}', coalesce(p_rows, '[]'::jsonb)),
         version = version + 1
   where name = p_name;
  if not found then
    raise exception 'app_put: % is not locked/created', p_name;
  end if;
end $$;

-- The row with this id, or NULL.
create or replace function app_find(p_rows jsonb, p_id text) returns jsonb
language sql immutable as $$
  select r from jsonb_array_elements(p_rows) as r where r ->> 'id' = p_id limit 1
$$;

-- rows[] without the row(s) matching a predicate key/value.
create or replace function app_without(p_rows jsonb, p_key text, p_value text)
returns jsonb language sql immutable as $$
  select coalesce(jsonb_agg(r), '[]'::jsonb)
    from jsonb_array_elements(p_rows) as r
   where r ->> p_key is distinct from p_value
$$;

-- rows[] with the row of this id replaced by p_row.
create or replace function app_replace(p_rows jsonb, p_id text, p_row jsonb)
returns jsonb language sql immutable as $$
  select coalesce(jsonb_agg(case when r ->> 'id' = p_id then p_row else r end), '[]'::jsonb)
    from jsonb_array_elements(p_rows) as r
$$;

-- Attendance queues live one document per event in app_queues.
create or replace function app_queue_lock(p_event_ids text[]) returns void
language plpgsql set search_path = public as $$
begin
  perform 1 from app_queues where event_id = any (p_event_ids) order by event_id for update;
end $$;

create or replace function app_queue_rows(p_event_id text) returns jsonb
language sql stable set search_path = public as $$
  select coalesce(
    (select doc -> 'rows' from app_queues where event_id = p_event_id),
    '[]'::jsonb)
$$;

create or replace function app_queue_delete(p_event_id text) returns void
language sql set search_path = public as $$
  delete from app_queues where event_id = p_event_id
$$;

