-- Create one study session (organizer): the activity + attendance event pair,
-- anchored on '<studyId>:<date>' so a repeated click returns the same
-- session. The session number is taken under the events lock, so two
-- sessions created at once never share one. A cancelled session keeps its
-- slot forever (review M2): refused with DETAIL 'session-slot-cancelled'.
--   p = { studyId, date, title, autoGenerated,
--         activityId, eventId, pathId, attendCode }  → { event }
create or replace function flow_create_study_session(p jsonb) returns jsonb
language plpgsql set search_path = public as $$
declare
  v_study_id text := p ->> 'studyId';
  v_key      text := (p ->> 'studyId') || ':' || (p ->> 'date');
  v_study    jsonb;
  v_events   jsonb;
  v_event    jsonb;
  v_acts     jsonb;
  v_act      jsonb;
  v_no       int;
  v_title    text;
  v_touched  text[] := '{}';
begin
  perform app_lock(array['activities', 'events', 'studies']);
  v_study := app_find(app_rows('studies'), v_study_id);
  if v_study is null then raise exception 'NOT_FOUND'; end if;
  if v_study ->> 'status' = 'finished' then raise exception 'CONFLICT'; end if;

  v_events := app_rows('events');
  select e into v_event from jsonb_array_elements(v_events) e
   where e ->> 'sourceRequestId' = v_key limit 1;
  if v_event is not null and v_event ->> 'status' = 'cancelled' then
    raise exception 'CONFLICT' using detail = 'session-slot-cancelled';
  end if;
  if v_event is not null then
    return jsonb_build_object('touched', '[]'::jsonb, 'event', v_event);
  end if;

  select coalesce(max((e ->> 'sessionNo')::int), 0) + 1 into v_no
    from jsonb_array_elements(v_events) e
   where e ->> 'studyId' = v_study_id;
  v_title := coalesce(nullif(p ->> 'title', ''), (v_study ->> 'title') || ' ' || v_no || '회차');

  v_acts := app_rows('activities');
  select a into v_act from jsonb_array_elements(v_acts) a
   where a ->> 'sourceRequestId' = v_key limit 1;
  if v_act is null then
    v_act := jsonb_build_object(
      'id', p ->> 'activityId',
      'title', v_title,
      'date', jsonb_build_object('start', p ->> 'date', 'end', null),
      'type', '스터디',
      'attendeeIds', '[]'::jsonb,
      'sourceRequestId', v_key);
    perform app_put('activities', v_acts || jsonb_build_array(v_act));
    v_touched := v_touched || array['activities'];
  end if;

  v_event := jsonb_build_object(
    'id', p ->> 'eventId',
    'title', v_title,
    'date', jsonb_build_object('start', p ->> 'date', 'end', null),
    'type', '스터디',
    'status', 'active',
    'pathId', p ->> 'pathId',
    'attendCode', p ->> 'attendCode',
    'activityId', v_act ->> 'id',
    'applicantIds', '[]'::jsonb,
    'presenterIds', '[]'::jsonb,
    'studyId', v_study_id,
    'sessionNo', v_no,
    'autoGenerated', coalesce((p ->> 'autoGenerated')::boolean, false),
    'sourceRequestId', v_key);
  perform app_put('events', v_events || jsonb_build_array(v_event));
  v_touched := v_touched || array['events'];

  return jsonb_build_object('touched', to_jsonb(v_touched), 'event', v_event);
end $$;

-- Correct a study session (organizer): title and/or start move on the event
-- and on its activity together — archives and term grouping key off the
-- activity's date (review M5). The anchor keeps the ORIGINAL date on
-- purpose: the old slot stays consumed. Empty title/date = keep.
--   p = { studyId, eventId, title, date }
create or replace function flow_update_study_session(p jsonb) returns jsonb
language plpgsql set search_path = public as $$
declare
  v_events jsonb;
  v_event  jsonb;
  v_acts   jsonb;
  v_act    jsonb;
  v_title  text := nullif(p ->> 'title', '');
  v_date   jsonb := case when coalesce(p ->> 'date', '') = '' then null
                         else jsonb_build_object('start', p ->> 'date', 'end', null) end;
begin
  perform app_lock(array['activities', 'events']);
  v_events := app_rows('events');
