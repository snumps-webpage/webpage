-- Append one audit row (API-SPEC §1-5) inside the caller's transaction — for
-- withdrawal-lifecycle entries, which are destruction evidence: the change
-- and its record commit together or not at all.
create or replace function app_audit(p_id text, p_at text, p_actor text, p_action text,
                                     p_target_tb text, p_target_id text)
returns void language sql set search_path = public as $$
  insert into audit_log (id, at, actor, action, target_tb, target_id, detail)
  values (p_id, p_at::timestamptz, p_actor, p_action, p_target_tb, p_target_id, null)
$$;

-- A member's own withdrawal request (MEM-07, API-SPEC §4-7). The triple
-- confirmation is checked here on the member as stored; an organizer of an
-- unfinished study must hand over first — read under a share lock, so a
-- handover accepted meanwhile cannot slip past. The status change and its
-- audit row commit together.
--   p = { memberId, ackInfo, ackDataPolicy, confirmName (trimmed), now,
--         auditId, auditAt }
create or replace function flow_request_withdrawal(p jsonb) returns jsonb
language plpgsql set search_path = public as $$
declare
  v_id      text := p ->> 'memberId';
  v_members jsonb;
  v_m       jsonb;
begin
  perform app_lock(array['members']);
  perform 1 from app_tables where name = 'studies' for share;
  v_members := app_rows('members');
  v_m := app_find(v_members, v_id);
  if v_m is null then raise exception 'NOT_FOUND'; end if;
  if v_m ->> 'status' = 'withdrawn' then raise exception 'CONFLICT'; end if;
  if not coalesce((p ->> 'ackInfo')::boolean, false)
     or not coalesce((p ->> 'ackDataPolicy')::boolean, false)
     or p ->> 'confirmName' is distinct from v_m ->> 'name' then
    raise exception 'VALIDATION_FAILED';
  end if;
  if exists (select 1 from jsonb_array_elements(app_rows('studies')) s
              where s -> 'organizerIds' ? v_id and s ->> 'status' <> 'finished') then
    raise exception 'CONFLICT';
  end if;

  perform app_put('members', app_replace(v_members, v_id, v_m || jsonb_build_object(
    'status', 'withdrawn',
    'statusChangedAt', p ->> 'now',
    'withdrawal', jsonb_build_object(
      'requestedAt', p ->> 'now',
      'previousStatus', v_m ->> 'status',
      'holdBy', null,
      'holdAt', null))));
  perform app_audit(p ->> 'auditId', p ->> 'auditAt', v_id, 'withdrawal.request', 'members', v_id);
  return jsonb_build_object('touched', jsonb_build_array('members'));
end $$;

-- The rest of the withdrawal lifecycle, each with its audit row:
--   cancel  — the member's own; restores the pre-withdrawal status
--   hold    — admin (ADM-17); pauses the grace period
--   release — admin; lifts the hold and restarts the one-month clock
--   p = { memberId, op, actorId, now, auditId, auditAt }
create or replace function flow_member_withdrawal(p jsonb) returns jsonb
language plpgsql set search_path = public as $$
declare
  v_id      text := p ->> 'memberId';
  v_op      text := p ->> 'op';
  v_members jsonb;
  v_m       jsonb;
  v_w       jsonb;
  v_next    jsonb;
begin
  if v_op not in ('cancel', 'hold', 'release') then raise exception 'VALIDATION_FAILED'; end if;
  perform app_lock(array['members']);
  v_members := app_rows('members');
  v_m := app_find(v_members, v_id);
  if v_m is null then raise exception 'NOT_FOUND'; end if;
  v_w := app_nullable(v_m -> 'withdrawal');
  if v_m ->> 'status' <> 'withdrawn' or v_w is null then
    -- nothing to cancel is "not found" for the member; a hold on it is a conflict
    if v_op = 'cancel' then raise exception 'NOT_FOUND'; end if;
    raise exception 'CONFLICT';
  end if;

  if v_op = 'cancel' then
    v_next := v_m || jsonb_build_object(
      'status', v_w ->> 'previousStatus',
      'statusChangedAt', p ->> 'now',
      'withdrawal', null);
  elsif v_op = 'hold' then
    v_next := v_m || jsonb_build_object('withdrawal', v_w || jsonb_build_object(
      'holdBy', p ->> 'actorId', 'holdAt', p ->> 'now'));
  else
    if app_nullable(v_w -> 'holdBy') is null then raise exception 'CONFLICT'; end if;
    v_next := v_m || jsonb_build_object('withdrawal', v_w || jsonb_build_object(
      'holdBy', null, 'holdAt', null, 'requestedAt', p ->> 'now'));
  end if;

  perform app_put('members', app_replace(v_members, v_id, v_next));
  perform app_audit(p ->> 'auditId', p ->> 'auditAt', p ->> 'actorId',
    case v_op when 'cancel' then 'withdrawal.cancel'
              when 'hold' then 'withdrawal.hold'
              else 'withdrawal.release-hold' end,
    'members', v_id);
  return jsonb_build_object('touched', jsonb_build_array('members'));
end $$;

-- Delete an activity record (admin record editor) — refused while an event,
-- a gallery entry or a seminar points at it; the check and the delete share
-- one lock, so a reference added meanwhile cannot be orphaned.
--   p = { id }
create or replace function flow_delete_activity(p jsonb) returns jsonb
language plpgsql set search_path = public as $$
declare
  v_id   text := p ->> 'id';
  v_acts jsonb;
begin
  perform app_lock(array['activities', 'events', 'gallery-dinner', 'seminars']);
  if exists (select 1 from jsonb_array_elements(app_rows('events')) e where e ->> 'activityId' = v_id)
     or exists (select 1 from jsonb_array_elements(app_rows('gallery-dinner')) g where g ->> 'activityId' = v_id)
     or exists (select 1 from jsonb_array_elements(app_rows('seminars')) s where s ->> 'activityId' = v_id)
  then
    raise exception 'CONFLICT';
  end if;
  v_acts := app_rows('activities');
  if app_find(v_acts, v_id) is null then raise exception 'NOT_FOUND'; end if;
  perform app_put('activities', app_without(v_acts, 'id', v_id));
  return jsonb_build_object('touched', jsonb_build_array('activities'));
end $$;

-- Delete a study record (admin record editor) — refused while it has
-- sessions. Returns its photo keys for cleanup after the commit.
--   p = { id }  → { assets }
create or replace function flow_delete_study(p jsonb) returns jsonb
language plpgsql set search_path = public as $$
declare
  v_id      text := p ->> 'id';
  v_studies jsonb;
  v_study   jsonb;
begin
  perform app_lock(array['events', 'studies']);
  if exists (select 1 from jsonb_array_elements(app_rows('events')) e where e ->> 'studyId' = v_id) then
    raise exception 'CONFLICT';
  end if;
  v_studies := app_rows('studies');
  v_study := app_find(v_studies, v_id);
  if v_study is null then raise exception 'NOT_FOUND'; end if;
  perform app_put('studies', app_without(v_studies, 'id', v_id));
  return jsonb_build_object(
    'touched', jsonb_build_array('studies'),
    'assets', coalesce(v_study -> 'photos', '[]'::jsonb));
end $$;

-- ---------------------------------------------------------------------------
-- 99. Privileges — flows and helpers run for the service role only.
--     (Guarded: PGlite has no Supabase roles.)
-- ---------------------------------------------------------------------------

do $$
declare
  f record;
  has_roles boolean := exists (select 1 from pg_roles where rolname = 'service_role');
begin
  for f in
    select p.oid::regprocedure as sig
      from pg_proc p join pg_namespace n on n.oid = p.pronamespace
     where n.nspname = 'public'
       and (p.proname like 'app\_%' or p.proname like 'flow\_%')
  loop
    execute format('revoke all on function %s from public', f.sig);
    if has_roles then
      execute format('revoke all on function %s from anon, authenticated', f.sig);
      execute format('grant execute on function %s to service_role', f.sig);
    end if;
  end loop;
end $$;
