-- Administrator-only study sessions. Ordinary organizer flows remain unchanged.
create or replace function app_assert_study_admin(actor_id text) returns void
language plpgsql set search_path = public as $$
begin
  perform 1 from app_tables where name = 'members' for share;
  if not exists (select 1 from jsonb_array_elements(app_rows('members')) m
    where m ->> 'id' = actor_id and m -> 'isAdmin' = 'true'::jsonb) then
    raise exception 'FORBIDDEN';
  end if;
end $$;
create or replace function flow_admin_study_create_session(p jsonb) returns jsonb
language plpgsql set search_path = public as $$
declare
  v_study_id text := p ->> 'studyId';
  v_key      text := (p ->> 'studyId') || ':' || (p ->> 'date');
  v_study    jsonb;
  v_events   jsonb;
  v_event    jsonb;
  v_acts     jsonb;
  v_act      jsonb;
  v_no       int;
  v_title    text;
  v_touched  text[] := '{}';
begin
  perform app_require(p, array['studyId', 'date', 'activityId', 'eventId', 'pathId', 'attendCode']);
  perform app_lock(array['activities', 'events', 'members', 'studies']);
  v_study := app_find(app_rows('studies'), v_study_id);
  if v_study is null then raise exception 'NOT_FOUND'; end if;
  perform app_assert_study_admin(p ->> 'actorId');

  v_events := app_rows('events');
  select e into v_event from jsonb_array_elements(v_events) e
   where e ->> 'sourceRequestId' = v_key limit 1;
  if v_event is not null and v_event ->> 'status' = 'cancelled' then
    raise exception 'CONFLICT' using detail = 'session-slot-cancelled';
  end if;
  if v_event is not null then
    return jsonb_build_object('touched', '[]'::jsonb, 'event', v_event);
  end if;

  select coalesce(max((e ->> 'sessionNo')::int), 0) + 1 into v_no
    from jsonb_array_elements(v_events) e
   where e ->> 'studyId' = v_study_id;
  v_title := coalesce(nullif(p ->> 'title', ''), (v_study ->> 'title') || ' ' || v_no || '회차');

  v_acts := app_rows('activities');
  select a into v_act from jsonb_array_elements(v_acts) a
   where a ->> 'sourceRequestId' = v_key limit 1;
  if v_act is null then
    v_act := jsonb_build_object(
      'id', p ->> 'activityId',
      'title', v_title,
      'date', jsonb_build_object('start', p ->> 'date', 'end', null),
      'type', '스터디',
      'attendeeIds', '[]'::jsonb,
      'studyId', p ->> 'studyId',
      'sourceRequestId', v_key);
    perform app_put('activities', v_acts || jsonb_build_array(v_act));
    v_touched := v_touched || array['activities'];
  end if;

  v_event := jsonb_build_object(
    'id', p ->> 'eventId',
    'title', v_title,
    'date', jsonb_build_object('start', p ->> 'date', 'end', null),
    'type', '스터디',
    'status', 'active',
    'pathId', p ->> 'pathId',
    'attendCode', p ->> 'attendCode',
    'activityId', v_act ->> 'id',
    'applicantIds', '[]'::jsonb,
    'presenterIds', '[]'::jsonb,
    'studyId', v_study_id,
    'sessionNo', v_no,
    'autoGenerated', coalesce((p ->> 'autoGenerated')::boolean, false),
    'sourceRequestId', v_key);
  perform app_put('events', v_events || jsonb_build_array(v_event));
  v_touched := v_touched || array['events'];

  return jsonb_build_object('touched', to_jsonb(v_touched), 'event', v_event);
end $$;
create or replace function flow_admin_study_session(p jsonb) returns jsonb
language plpgsql set search_path = public as $$
declare
  v_study jsonb;
  v_events jsonb;
  v_event jsonb;
  v_acts jsonb;
  v_act jsonb;
  v_result jsonb;
  v_date jsonb;
  v_ids jsonb;
begin
  perform app_require(p, array['studyId', 'actorId', 'auditId', 'auditAt', 'op']);
  perform app_lock(array['activities', 'events', 'members', 'studies']);
  perform app_assert_study_admin(p ->> 'actorId');
  v_study := app_find(app_rows('studies'), p ->> 'studyId');
  if v_study is null then raise exception 'NOT_FOUND'; end if;
  if p ->> 'op' = 'create' then
    v_result := flow_admin_study_create_session(p);
    -- Idempotent repeat must not append another audit row.
    if v_result -> 'touched' = '[]'::jsonb then return v_result; end if;
    v_event := v_result -> 'event';
  else
    perform app_require(p, array['eventId']);
    v_events := app_rows('events');
    v_event := app_find(v_events, p ->> 'eventId');
    if v_event is null or v_event ->> 'studyId' is distinct from p ->> 'studyId' then
      raise exception 'NOT_FOUND';
    end if;
    if v_event ->> 'status' = 'cancelled' then
      raise exception 'CONFLICT' using detail = 'session-cancelled';
    end if;
    v_acts := app_rows('activities');
    v_act := app_find(v_acts, v_event ->> 'activityId');
    if v_act is null or v_act ->> 'studyId' is distinct from p ->> 'studyId' then
      raise exception 'NOT_FOUND';
    end if;
    if p ->> 'op' = 'cancel' then
      v_event := v_event || jsonb_build_object('status', 'cancelled');
      perform app_put('events', app_replace(v_events, v_event ->> 'id', v_event));
      v_result := jsonb_build_object('touched', jsonb_build_array('events'));
    elsif p ->> 'op' = 'update' then
      v_date := case when coalesce(p ->> 'date', '') = '' then v_event -> 'date'
        else jsonb_build_object('start', p ->> 'date', 'end', null) end;
      v_event := v_event || jsonb_build_object('title', coalesce(nullif(p ->> 'title',''), v_event ->> 'title'), 'date', v_date);
      v_act := v_act || jsonb_build_object('title', v_event ->> 'title', 'date', v_date);
      perform app_put('events', app_replace(v_events, v_event ->> 'id', v_event));
      perform app_put('activities', app_replace(v_acts, v_act ->> 'id', v_act));
      v_result := jsonb_build_object('touched', jsonb_build_array('events','activities'));
    elsif p ->> 'op' = 'attendance' then
      if jsonb_typeof(p -> 'selectedIds') is distinct from 'array' or exists (
        select 1 from jsonb_array_elements(p -> 'selectedIds') x
        where jsonb_typeof(x) <> 'string' or not (v_study -> 'participantIds' @> jsonb_build_array(x))) then
        raise exception 'VALIDATION_FAILED';
      end if;
      -- The same sheet merge as the organizer: retain walk-in attendees.
      select coalesce(jsonb_agg(x), '[]'::jsonb) into v_ids from (
        select distinct x from jsonb_array_elements((v_act -> 'attendeeIds') || (p -> 'selectedIds')) x
        where not (v_study -> 'participantIds' @> jsonb_build_array(x))
          or p -> 'selectedIds' @> jsonb_build_array(x)
      ) chosen;
      perform app_put('activities', app_replace(v_acts, v_act ->> 'id',
        v_act || jsonb_build_object('attendeeIds', v_ids)));
      v_result := jsonb_build_object('touched', jsonb_build_array('activities'));
    else
      raise exception 'VALIDATION_FAILED';
    end if;
  end if;
  perform app_audit(p ->> 'auditId', p ->> 'auditAt', p ->> 'actorId',
    'study.session-' || (p ->> 'op'), 'events', v_event ->> 'id');
  return v_result || jsonb_build_object('event', v_event);
end $$;

do $$
declare f text;
begin
  foreach f in array array['app_assert_study_admin(text)', 'flow_admin_study_create_session(jsonb)', 'flow_admin_study_session(jsonb)'] loop
    execute 'revoke all on function ' || f || ' from public';
    if exists(select 1 from pg_roles where rolname = 'anon') then execute 'revoke all on function ' || f || ' from anon'; end if;
    if exists(select 1 from pg_roles where rolname = 'authenticated') then execute 'revoke all on function ' || f || ' from authenticated'; end if;
    if exists(select 1 from pg_roles where rolname = 'service_role') then execute 'grant execute on function ' || f || ' to service_role'; end if;
  end loop;
end $$;
