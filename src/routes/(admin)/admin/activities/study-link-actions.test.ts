function post(fields: Record<string, string>) {
  const body = new FormData();
  for (const [k, v] of Object.entries(fields)) body.set(k, v);
  return {
    request: new Request("http://localhost/admin/activities", {
      method: "POST",
      body,
    }),
    locals: admin,
  } as never;
}

const activity = (id: string, type: string, studyId: string | null) => ({
  id,
  title: id,
  date: { start: "2025-03-01T19:00:00+09:00", end: null },
  type,
  attendeeIds: [],
  studyId,
  sourceRequestId: null,
});

const study = (id: string, title: string, semester: string) => ({
  id,
  title,
  semester,
  textbook: "",
  description: "",
  note: "",
  organizerIds: ["org"],
  participantIds: ["org"],
  pendingParticipantIds: [],
  pendingTransfer: null,
  schedule: [],
  transferHistory: [],
  photos: [],
  status: "finished",
  sourceRequestId: null,
});

/** An attendance event hung off an activity; a non-null studyId is a session. */
const event = (id: string, activityId: string, studyId: string | null) => ({
  id,
  title: id,
  date: { start: "2025-03-01T19:00:00+09:00", end: null },
  type: studyId ? "스터디" : "세미나",
  status: "expired",
  pathId: `path-${id}`,
  attendCode: "1234",
  activityId,
  applicantIds: [],
  presenterIds: [],
  studyId,
  sessionNo: studyId ? 1 : null,
  autoGenerated: false,
  sourceRequestId: studyId ? `${studyId}:2025-03-01` : null,
});

type Refusal = { status: number; data: { error: string; message: string } };

