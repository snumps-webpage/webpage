describe("?/update while linked to a study (D-000087)", () => {
  const update = (id: string, fields: Record<string, string>) =>
    actions.update(post({ id, title: id, type: "스터디", ...fields }));

  it("refuses moving a linked activity off '스터디', writing nothing", async () => {
    const before = await version();
    const result = (await update("a-linked", {
      type: "회의",
    })) as unknown as Refusal;
    expect(result).toMatchObject({
      status: 400,
      data: { error: "VALIDATION_FAILED" },
    });
    expect(result.data.message).toContain("연결");
    expect(await version()).toBe(before);
    expect(await typeOf("a-linked")).toBe("스터디");
  });

  it("refuses a type change that comes with other edits, writing none of them", async () => {
    const before = await version();
    const result = await update("a-linked", { type: "회의", title: "새 제목" });
    expect(result).toMatchObject({
      status: 400,
      data: { error: "VALIDATION_FAILED" },
    });
    expect(await version()).toBe(before);
    expect(await titleOf("a-linked")).toBe("a-linked");
  });

  it("lets an unlinked study activity change its type", async () => {
    const result = await update("a-study", { type: "회의" });
    expect(result).toMatchObject({
      success: true,
      operation: "activityUpdated",
    });
    expect(await typeOf("a-study")).toBe("회의");
  });

  // D-000114: a linked activity's type may only move TO '스터디'.
  it("refuses moving a linked '회의' activity to '세미나', writing nothing", async () => {
    const before = await version();
    const result = await update("a-linked-meeting", { type: "세미나" });
    expect(result).toMatchObject({
      status: 400,
      data: { error: "VALIDATION_FAILED" },
    });
    expect(await version()).toBe(before);
    expect(await typeOf("a-linked-meeting")).toBe("회의");
  });

  it("lets a linked '회의' activity move to '스터디'", async () => {
    const result = await update("a-linked-meeting", { type: "스터디" });
    expect(result).toMatchObject({
      success: true,
      operation: "activityUpdated",
    });
    expect(await typeOf("a-linked-meeting")).toBe("스터디");
  });

  it("keeps an unchanged non-'스터디' type of a linked activity", async () => {
    const result = await update("a-linked-meeting", {
      type: "회의",
      title: "정리 회의",
    });
    expect(result).toMatchObject({ success: true });
    expect(await titleOf("a-linked-meeting")).toBe("정리 회의");
    expect(await typeOf("a-linked-meeting")).toBe("회의");
  });

  // D-000107: the editor disables the type select of a linked activity, and a
  // disabled select is not submitted — a missing type is no change.
  it("saves the other fields when the form carries no type", async () => {
    for (const id of ["a-linked", "a-linked-meeting"]) {
      const before = await typeOf(id);
      const result = await actions.update(post({ id, title: `${id} 새 제목` }));
      expect(result).toMatchObject({
        success: true,
        operation: "activityUpdated",
      });
      expect(await titleOf(id)).toBe(`${id} 새 제목`);
      expect(await typeOf(id)).toBe(before);
    }
  });

  it("still edits a linked activity's other fields", async () => {
    const result = await update("a-linked", {
      title: "해석학 1회",
      start: "2025-03-08T19:00",
    });
    expect(result).toMatchObject({
      success: true,
      operation: "activityUpdated",
    });
    const row = (await getTable("activities")).find((a) => a.id === "a-linked");
    expect(row).toMatchObject({ title: "해석학 1회", type: "스터디" });
    expect(row?.date.start).not.toBe("2025-03-01T19:00:00+09:00");
    expect(row?.studyId).toBe("s1");
  });
});

// D-000098: a refused edit hands back what was typed, for that card.
describe("?/update refusals return the submitted values", () => {
  it("returns them with a type refusal", async () => {
    const result = await actions.update(
      post({ id: "a-linked", title: "고친 제목", type: "회의" }),
    );
    expect(result).toMatchObject({
      status: 400,
      data: {
        error: "VALIDATION_FAILED",
        id: "a-linked",
        message: expect.stringContaining("연결"),
        values: { title: "고친 제목", type: "회의", start: "", end: "" },
      },
    });
  });

  it("returns them with a paired-owner conflict", async () => {
    const result = await actions.update(
      post({
        id: "a-session",
        title: "회차 새 이름",
        type: "스터디",
        start: "2025-03-08T00:00",
      }),
    );
    expect(result).toMatchObject({
      status: 409,
      data: {
        error: "CONFLICT",
        id: "a-session",
        message: expect.stringContaining("스터디 관리"),
        values: {
          title: "회차 새 이름",
          type: "스터디",
          start: "2025-03-08T00:00",
        },
      },
    });
  });

  it("returns no values for an activity that is gone", async () => {
    const result = (await actions.update(
      post({ id: "missing", title: "x", type: "회의" }),
    )) as unknown as { status: number; data: Record<string, unknown> };
    expect(result).toMatchObject({ status: 404 });
    expect(result.data.values).toBeUndefined();
  });
});

describe("?/setStudy on a study-session activity (D-000088)", () => {
  it("refuses relinking it to another study, writing nothing", async () => {
    const before = await version();
    const result = (await actions.setStudy(
      post({ id: "a-session", studyId: "s2" }),
    )) as unknown as Refusal;
    expect(result).toMatchObject({
      status: 400,
      data: { error: "VALIDATION_FAILED" },
    });
    expect(result.data.message).toContain("회차");
    expect(await version()).toBe(before);
    expect(await studyIdOf("a-session")).toBe("s1");
  });

  it("refuses unlinking it, writing nothing", async () => {
    const before = await version();
    const result = await actions.setStudy(
      post({ id: "a-session", studyId: "" }),
    );
    expect(result).toMatchObject({
      status: 400,
      data: { error: "VALIDATION_FAILED" },
    });
    expect(await version()).toBe(before);
    expect(await studyIdOf("a-session")).toBe("s1");
  });

  it("still relinks a migrated activity that no session points at", async () => {
    const result = await actions.setStudy(
      post({ id: "a-linked", studyId: "s2" }),
    );
    expect(result).toMatchObject({ success: true, operation: "studyLinked" });
    expect(await studyIdOf("a-linked")).toBe("s2");
  });

  it("does not count a seminar attendance event as a session", async () => {
    const result = await actions.setStudy(
      post({ id: "a-seminar", studyId: "s2" }),
    );
    expect(result).toMatchObject({ success: true, operation: "studyLinked" });
    expect(await studyIdOf("a-seminar")).toBe("s2");
  });
});

describe("?/setStudy", () => {
  it("links a study activity to the chosen study", async () => {
    const result = await actions.setStudy(
      post({ id: "a-study", studyId: "s2" }),
    );
    expect(result).toMatchObject({ success: true, operation: "studyLinked" });
    expect(await studyIdOf("a-study")).toBe("s2");
  });

  it("unlinks when the study is left empty", async () => {
    const result = await actions.setStudy(
      post({ id: "a-linked", studyId: "" }),
    );
    expect(result).toMatchObject({ success: true, operation: "studyLinked" });
    expect(await studyIdOf("a-linked")).toBeNull();
  });

  it("refuses an activity of another type, writing nothing", async () => {
    const before = await version();
    const result = await actions.setStudy(
      post({ id: "a-meeting", studyId: "s1" }),
    );
    expect(result).toMatchObject({
      status: 400,
      data: { error: "VALIDATION_FAILED", message: expect.any(String) },
    });
    expect(await version()).toBe(before);
    expect(await studyIdOf("a-meeting")).toBeNull();
  });

  it("refuses a study that does not exist, writing nothing", async () => {
    const before = await version();
    const result = (await actions.setStudy(
      post({ id: "a-study", studyId: "nope" }),
    )) as unknown as Refusal;
    expect(result).toMatchObject({
      status: 400,
      data: { error: "VALIDATION_FAILED" },
    });
    expect(result.data.message).toContain("스터디");
    expect(await version()).toBe(before);
  });

  it("says the activity is gone, in other words than a missing study", async () => {
    const gone = (await actions.setStudy(
      post({ id: "missing", studyId: "s1" }),
    )) as unknown as Refusal;
    const noStudy = (await actions.setStudy(
      post({ id: "a-study", studyId: "nope" }),
    )) as unknown as Refusal;
    expect(gone).toMatchObject({ status: 404, data: { error: "NOT_FOUND" } });
    expect(gone.data.message).toContain("활동");
    expect(gone.data.message).not.toBe(noStudy.data.message);
  });
});
