describe("memberActivityIndex", () => {
  it("leaves hidden activities and unpublished seminars out of the public count", async () => {
    const activityOf = await memberActivityIndex({ publicOnly: true });
    const m1 = activityOf(
      memberRow({ id: "m1", name: "김수학", legacyMemberId: "L1" }),
    );

    expect(m1.attended.map((a) => a.id)).toEqual([
      "a-dinner",
      "a-sem",
      "a-old",
    ]);
    expect(m1.hostedSeminars.map((s) => s.id).sort()).toEqual([
      "s-old",
      "s-pub",
    ]);
    // 최근 세미나·스터디 참석은 모두 숨김 활동뿐 — 공개 면에서는 비활동
    expect(m1.active).toBe(false);
  });

  it("counts everything for the admin view", async () => {
    const activityOf = await memberActivityIndex({ publicOnly: false });
    const m1 = activityOf(
      memberRow({ id: "m1", name: "김수학", legacyMemberId: "L1" }),
    );

    expect(m1.attended.map((a) => a.id)).toEqual([
      "a-dinner",
      "a-cancelled",
      "a-draft",
      "a-sem",
      "a-old",
    ]);
    expect(m1.hostedSeminars.map((s) => s.id).sort()).toEqual([
      "s-draft",
      "s-old",
      "s-pub",
    ]);
    expect(m1.active).toBe(true);
  });
});

describe("getPublicMembers", () => {
  it("merges a rejoined member's legacy records into one row", async () => {
    const roster = await getPublicMembers();
    expect(roster.map((m) => m.id)).toEqual(["m1", "L2"]);

    const m1 = roster.find((m) => m.id === "m1")!;
    expect(m1.activity).toEqual({
      active: false,
      hostedSeminars: [
        { id: "s-pub", title: "세미나 s-pub", semester: "26-2" },
        { id: "s-old", title: "세미나 s-old", semester: "26-2" },
      ],
      hostedStudies: [{ id: "st1", title: "해석학", semester: "23-2" }],
      countsByType: { 회식: 1, 세미나: 1, 스터디: 1 },
    });
  });

  it("carries no attendance list", async () => {
    const json = JSON.stringify(await getPublicMembers());
    expect(json).not.toContain('"attended"');
    expect(json).not.toContain('"attendeeIds"');
  });
});

describe("getPublicMember", () => {
  it("returns the public profile and the merged public activity", async () => {
    const result = await getPublicMember("m1");
    expect(result).not.toBeNull();
    expect(result).not.toHaveProperty("redirectTo");
    const { member, activity } = result as Exclude<
      typeof result,
      null | { redirectTo: string }
    >;
    expect(member).toEqual({
      id: "m1",
      name: "김수학",
      department: "수리과학부",
      joinedAt: "2024-03-01",
      roles: [],
    });
    expect(activity.attended.map((a) => a.id)).toEqual([
      "a-dinner",
      "a-sem",
      "a-old",
    ]);
  });

  it("answers a rejoined member's legacy id with the current page", async () => {
    expect(await getPublicMember("L1")).toEqual({ redirectTo: "/members/m1" });
  });

  it("shows a legacy member who never rejoined under the legacy id", async () => {
    const result = await getPublicMember("L2");
    expect(result).toMatchObject({ member: { id: "L2", name: "박옛날" } });
  });

  it("knows no withdrawn or unknown member", async () => {
    expect(await getPublicMember("m2")).toBeNull();
    expect(await getPublicMember("nobody")).toBeNull();
  });
});
