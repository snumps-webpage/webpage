/**
 * 공개 명단의 활동 정도 (snumps-webpage/D-000041·046·051·052).
 *
 * - 공개 집계는 회원 면과 같은 숨김 규칙을 따른다: 숨김 활동(비공개 세미나의
 *   활동, 이벤트가 모두 취소된 활동)과 공개 아카이브에 없는 세미나는 세지 않는다.
 * - 재가입 회원은 새 id와 legacy id의 기록을 합쳐 한 사람으로 센다.
 * - 명단 행에는 참석 목록을 싣지 않는다(공개 페이지에만).
 */

const DAY = 86_400_000;
const daysAgo = (n: number) => new Date(Date.now() - n * DAY).toISOString();

function memberRow(over: Partial<Member> & Pick<Member, "id" | "name">) {
  return {
    department: "수리과학부",
    joinedAt: "2024-03-01",
    status: "regular" as const,
    statusChangedAt: nowKstIso(),
    withdrawal: null,
    isAlumni: false,
    alumniRevoked: false,
    roles: [],
    isAdmin: false,
    publicContact: null,
    alumniRevocationReason: null,
    project: null,
    legacyMemberId: null,
    sourceRequestId: null,
    ...over,
  };
}

