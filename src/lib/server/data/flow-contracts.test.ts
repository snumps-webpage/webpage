// LA43-4 — the other two helpers have no single TS twin; their rules are
// pinned here by truth table instead.
describe("app_seminar_status / app_is_seminar_event", () => {
  const status = async (row: object) =>
    (
      await __sql<{ s: string }>("select app_seminar_status($1::jsonb) as s", [
        JSON.stringify(row),
      ])
    )[0].s;

  it("reads a missing or null status as published, anything else as written", async () => {
    expect(await status({})).toBe("published");
    expect(await status({ publicationStatus: null })).toBe("published");
    expect(await status({ publicationStatus: "cancelled" })).toBe("cancelled");
  });

  const belongs = async (event: object, seminar: object) =>
    (
      await __sql<{ b: boolean }>(
        "select app_is_seminar_event($1::jsonb, $2::jsonb) as b",
        [JSON.stringify(event), JSON.stringify(seminar)],
      )
    )[0].b;

  it("counts an event anchored to the seminar, or on its activity", async () => {
    const s = { id: "s1", activityId: "a1" };
    expect(
      await belongs({ sourceRequestId: "seminar:s1", activityId: "x" }, s),
    ).toBe(true);
    expect(await belongs({ sourceRequestId: null, activityId: "a1" }, s)).toBe(
      true,
    );
    expect(
      await belongs({ sourceRequestId: "seminar:s2", activityId: "x" }, s),
    ).toBe(false);
    expect(
      await belongs(
        { sourceRequestId: null, activityId: "a1" },
        { id: "s1", activityId: null },
      ),
    ).toBe(false);
  });
});
