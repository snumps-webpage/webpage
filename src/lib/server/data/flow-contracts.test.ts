// LA43-1 🔴 — every migrated seminar is published with no anchor and
// announcedAt null, so the board offers "공지 재발송" on all of them.
describe("publishing a seminar linked by activityId (no anchor)", () => {
  it("reuses its activity and event instead of creating a second pair", async () => {
    await put("seminars", [legacySeminar()]);
    await put("activities", [legacyActivity]);
    await put("events", [legacyEvent]);

    await publishSeminar("s1");

    expect((await getTable("activities")).map((a) => a.id)).toEqual(["a1"]);
    expect((await getTable("events")).map((e) => e.id)).toEqual(["e1"]);
    expect((await getTable("seminars"))[0].activityId).toBe("a1");

    await cancelSeminar("s1", { memberId: "admin", isAdmin: true });
    expect((await getTable("events"))[0].status).toBe("cancelled");
    await expectTablesValid();
  });

  it("keeps the seminar and an anchored event on the same activity", async () => {
    await put("seminars", [legacySeminar()]);
    await put("activities", [legacyActivity]);
    await put("events", [{ ...legacyEvent, sourceRequestId: "seminar:s1" }]);

    await publishSeminar("s1");

    const [event] = await getTable("events");
    expect((await getTable("activities")).map((a) => a.id)).toEqual(["a1"]);
    expect((await getTable("seminars"))[0].activityId).toBe(event.activityId);
  });
});

