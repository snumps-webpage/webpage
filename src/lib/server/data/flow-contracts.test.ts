// LA43-3 — rejecting one approved check-in removed the member's credit even
// when another approved check-in on the same activity still justified it.
describe("rejecting an approved check-in", () => {
  it("keeps the credit another approved check-in on the activity justifies", async () => {
    const e1 = await createEventWithActivity({
      title: "세미나",
      startIso: FUTURE,
      type: "세미나",
      status: "active",
    });
    // a second session of the same activity
    const events = await getTable("events");
    const e2 = { ...events[0], id: "e2", pathId: "p2", attendCode: "c2" };
    await put("events", [...events, e2]);
    await invalidateCache("table_events");

    const r1 = await checkIn(e1, "m1");
    const r2 = await checkIn(e2 as never, "m1");
    await approveAttendance(e1.id, r1.id);
    await approveAttendance("e2", r2.id);

    await rejectAttendance(e1.id, r1.id);

    const activity = (await getTable("activities"))[0];
    expect(activity.attendeeIds).toContain("m1");
    expect((await getQueue("e2"))[0].status).toBe("approved");
  });

  it("keeps a presenter's credit", async () => {
    const e = await createEventWithActivity({
      title: "세미나",
      startIso: FUTURE,
      type: "세미나",
      status: "active",
      presenterIds: ["p1"],
    } as never);
    const r = await checkIn(e, "p1");
    await approveAttendance(e.id, r.id);
    await rejectAttendance(e.id, r.id);
    expect((await getTable("activities"))[0].attendeeIds).toContain("p1");
  });
});

