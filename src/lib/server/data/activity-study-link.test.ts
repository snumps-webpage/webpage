/**
 * 활동↔스터디 연결: activities 행마다 nullable `studyId`. 이 필드 전의 행은
 * 그 활동에 걸린 출석 이벤트의 studyId로 채우고(없으면 null), 활동을 만드는
 * 모든 경로가 키를 직접 쓴다 — 저장 행이 스키마 기본값에 기대지 않는다.
 */

const MIGRATION_FILE = readFileSync(
  "supabase/migrations/20261015000000_activity_study_link.sql", // vitest runs from the repo root
  "utf8",
);
// The backfill statement alone — PGlite's query takes one statement, and the
// rest of the file (the flows) is already loaded with the migrations.
const start = MIGRATION_FILE.indexOf("update app_tables");
const BACKFILL = MIGRATION_FILE.slice(
  start,
  MIGRATION_FILE.indexOf(";", start) + 1,
);

const codeOf = (e: unknown) => (e instanceof AppError ? e.code : String(e));
const future = () => toKstIso(new Date(Date.now() + 24 * 60 * 60 * 1000));

const put = (name: string, rows: unknown[]) =>
  __putRawDoc("table", name, { schemaVersion: 1, rows });
const rawRows = async (name: string) =>
  (
    (await __docs("table")).get(name)?.doc as
      { rows: Record<string, unknown>[] } | undefined
  )?.rows ?? [];
const version = async (name: string) =>
  (await __docs("table")).get(name)?.version;

const activity = (id: string, extra: object = {}) => ({
  id,
  title: id,
  date: { start: "2026-09-01T19:00:00+09:00", end: null },
  type: "스터디",
  attendeeIds: [],
  sourceRequestId: null,
  ...extra,
});
const event = (id: string, activityId: string, studyId: string | null) => ({
  id,
  title: id,
  date: { start: "2026-09-01T19:00:00+09:00", end: null },
  type: studyId ? "스터디" : "세미나",
  status: "active",
  pathId: `p-${id}`,
  attendCode: `c-${id}`,
  activityId,
  applicantIds: [],
  presenterIds: [],
  studyId,
  sessionNo: studyId ? 1 : null,
  autoGenerated: false,
  sourceRequestId: null,
});

async function seedStudy(over: Partial<Study> = {}): Promise<Study> {
  const s: Study = {
    id: newId(),
    title: "해석학",
    semester: "26-2",
    textbook: "",
    description: "",
    note: "",
    organizerIds: ["org"],
    participantIds: ["org"],
    pendingParticipantIds: [],
    pendingTransfer: null,
    schedule: [],
    transferHistory: [],
    photos: [],
    status: "ongoing",
    sourceRequestId: null,
    ...over,
  };
  await mutate("studies", (rows) => [...rows, s]);
  return s;
}

beforeEach(async () => {
  await __reset();
  _resetDataLayerForTests({ backoffBaseMs: 1 });
  for (const t of [
    "activities",
    "events",
    "seminars",
    "seminar-requests",
    "studies",
  ])
    await invalidateCache(`table_${t}`);
});

describe("20261015000000_activity_study_link backfill", () => {
  it("takes the study of the activity's attendance event, null otherwise, and keeps a written value", async () => {
    await put("activities", [
      activity("a-study"),
      activity("a-seminar", { type: "세미나" }),
      activity("a-bare", { type: "회의" }),
      activity("a-kept", { studyId: "st-kept" }),
      activity("a-unlinked", { studyId: null }),
    ]);
    await put("events", [
      event("e-seminar", "a-seminar", null),
      event("e-study", "a-study", "st1"),
      event("e-kept", "a-kept", "st-other"),
      event("e-unlinked", "a-unlinked", "st-other"),
    ]);

    await __sql(BACKFILL);

    const rows = await rawRows("activities");
    expect(rows.map((r) => [r.id, r.studyId])).toEqual([
      ["a-study", "st1"],
      ["a-seminar", null],
      ["a-bare", null],
      ["a-kept", "st-kept"],
      ["a-unlinked", null],
    ]);
    for (const r of rows) expect("studyId" in r).toBe(true);
    expect(rows[0].title).toBe("a-study"); // the rest of the row untouched
  });

  it("writes every row lacking the key when there are no events at all", async () => {
    await put("activities", [activity("a1"), activity("a2")]);
    await __sql(BACKFILL);
    expect((await rawRows("activities")).map((r) => r.studyId)).toEqual([
      null,
      null,
    ]);
  });

  it("is idempotent: a second run changes nothing, not even the version", async () => {
    await put("activities", [activity("a1")]);
    await put("events", [event("e1", "a1", "st1")]);
    await __sql(BACKFILL);
    const first = await version("activities");

    await __sql(BACKFILL);

    expect(await version("activities")).toBe(first);
    expect((await rawRows("activities"))[0].studyId).toBe("st1");
  });
});

describe("every activity writer writes studyId itself (no default relied on)", () => {
  afterEach(expectTablesValid);

  it("flow_create_study_session links the session's activity to its study", async () => {
    const study = await seedStudy();
    const created = await createStudySession(study, future(), {
      autoGenerated: false,
    });

    const [raw] = await rawRows("activities");
    expect(raw.id).toBe(created.activityId);
    expect(raw).toHaveProperty("studyId", study.id);
    expect(ActivitySchema.strict().safeParse(raw).success).toBe(true);
  });

  it("flow_publish_seminar writes a null study on the seminar's activity", async () => {
    const request = await submitSeminarRequest({
      title: "공개 세미나",
      description: "",
      prerequisites: "",
      duration: "60",
      preferredTiming: "",
      presenterIds: ["m-a"],
      attachment: "",
      requesterId: "m-a",
    });
    await approveSeminar(request.id);
    const [sem] = await getTable("seminars");
    await scheduleSeminar(sem.id, {
      startsAt: future(),
      startTime: null,
      endsAt: null,
      location: "27동",
    });
    const { activityId } = await publishSeminar(sem.id);

    const [raw] = await rawRows("activities");
    expect(raw.id).toBe(activityId);
    expect(raw).toHaveProperty("studyId", null);
    expect(ActivitySchema.strict().safeParse(raw).success).toBe(true);
  });

  it("createActivity writes a null study", async () => {
    await createActivity({
      title: "정기 회의",
      date: { start: "2026-09-01T19:00:00+09:00", end: null },
      type: "회의",
    });
    expect((await rawRows("activities"))[0]).toHaveProperty("studyId", null);
  });

  it("createEventWithActivity writes a null study", async () => {
    await createEventWithActivity({
      title: "정기 회의",
      startIso: "2026-09-01T19:00:00+09:00",
      type: "회의",
    });
    expect((await rawRows("activities"))[0]).toHaveProperty("studyId", null);
  });
});

describe("flow_set_activity_study", () => {
  afterEach(expectTablesValid);

  it("links an activity to a study and unlinks it again", async () => {
    const study = await seedStudy();
    const { id } = await createActivity({
      title: "독서 모임",
      date: { start: "2026-09-01T19:00:00+09:00", end: null },
      type: "스터디",
    });

    const linked = await callFlow("flow_set_activity_study", {
      activityId: id,
      studyId: study.id,
    });
    expect(linked.touched).toEqual(["activities"]);
    expect((await rawRows("activities"))[0]).toMatchObject({
      id,
      studyId: study.id,
      title: "독서 모임",
    });

    await callFlow("flow_set_activity_study", {
      activityId: id,
      studyId: null,
    });
    expect((await rawRows("activities"))[0]).toHaveProperty("studyId", null);
  });

  it("refuses an activity that does not exist, writing nothing", async () => {
    const study = await seedStudy();
    await createActivity({
      title: "독서 모임",
      date: { start: "2026-09-01T19:00:00+09:00", end: null },
      type: "스터디",
    });
    const before = await version("activities");
    await expect(
      callFlow("flow_set_activity_study", {
        activityId: "missing",
        studyId: study.id,
      }),
    ).rejects.toSatisfy((e) => codeOf(e) === "NOT_FOUND");
    expect(await version("activities")).toBe(before);
  });

  it("refuses a study that does not exist, writing nothing", async () => {
    const { id } = await createActivity({
      title: "독서 모임",
      date: { start: "2026-09-01T19:00:00+09:00", end: null },
      type: "스터디",
    });
    const before = await version("activities");
    await expect(
      callFlow("flow_set_activity_study", { activityId: id, studyId: "nope" }),
    ).rejects.toSatisfy((e) => codeOf(e) === "NOT_FOUND");
    expect(await version("activities")).toBe(before);
    expect((await rawRows("activities"))[0]).toHaveProperty("studyId", null);
  });

  // snumps-webpage/D-000062: the two NOT_FOUNDs carry their reason, so the
  // admin screen can say which one is gone.
  it.each([
    ["activity", { activityId: "missing", studyId: null }],
    ["study", { activityId: "a1", studyId: "nope" }],
  ])("names the missing %s in the NOT_FOUND detail", async (detail, args) => {
    await put("activities", [activity("a1", { studyId: null })]);
    const messages = { activity: "활동 없음", study: "스터디 없음" };
    await expect(
      callFlow("flow_set_activity_study", args, { messages }),
    ).rejects.toSatisfy(
      (e) =>
        e instanceof AppError &&
        e.code === "NOT_FOUND" &&
        e.userMessage === messages[detail as keyof typeof messages],
    );
  });

  it.each([
    ["activityId", { studyId: null }],
    ["studyId", { activityId: "a1" }],
  ])("refuses a call without %s", async (_key, args) => {
    await put("activities", [activity("a1", { studyId: null })]);
    await expect(callFlow("flow_set_activity_study", args)).rejects.toSatisfy(
      (e) => codeOf(e) === "VALIDATION_FAILED",
    );
  });
});
