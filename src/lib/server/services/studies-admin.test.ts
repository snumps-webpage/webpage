import { beforeEach, expect, it, vi } from "vitest";
vi.mock(
  "$lib/server/data/store",
  () => import("$lib/server/data/store-memory"),
);
import {
  __reset,
  __putRawDoc,
  __auditRows,
  rpc,
} from "$lib/server/data/store-memory";
import {
  _resetDataLayerForTests,
  getTable,
  invalidateTable,
} from "$lib/server/data/tables";
import { createStudySession } from "./studies";

const date = "2026-11-03T19:00:00+09:00";
const study = (id: string, status = "finished") => ({
  id,
  title: "해석학",
  semester: "26-2",
  textbook: "",
  description: "",
  note: "",
  organizerIds: ["org"],
  participantIds: ["org", "p1"],
  pendingParticipantIds: [],
  pendingTransfer: null,
  schedule: [],
  transferHistory: [],
  photos: [],
  status,
  sourceRequestId: null,
});
const member = (id: string, isAdmin = false) => ({
  id,
  name: id,
  department: "수리",
  joinedAt: "2024-03-01",
  status: "regular",
  statusChangedAt: date,
  withdrawal: null,
  isAlumni: false,
  alumniRevoked: false,
  alumniRevocationReason: null,
  roles: [],
  isAdmin,
  publicContact: null,
  project: null,
  legacyMemberId: null,
  sourceRequestId: null,
});
import * as adminApi from "./studies-admin";
const api = async () => adminApi;
beforeEach(async () => {
  await __reset();
  _resetDataLayerForTests({ backoffBaseMs: 1 });
  for (const t of ["members", "studies", "activities", "events"] as const)
    await invalidateTable(t);
  await __putRawDoc("table", "members", {
    schemaVersion: 1,
    rows: [member("admin", true), member("org"), member("p1")],
  });
  await __putRawDoc("table", "studies", {
    schemaVersion: 1,
    rows: [study("s1"), study("s2", "cancelled")],
  });
});
it.each(["s1", "s2"])(
  "admin creates, edits and cancels a session on closed %s while preserving study state",
  async (id) => {
    const a = await api();
    const e = await a.createAdminStudySession(id, date, "첫 회차", "admin");
    await a.updateAdminStudySession(
      id,
      e.id,
      { title: "정정", dateIso: "2026-11-04T19:00:00+09:00" },
      "admin",
    );
    expect((await getTable("activities"))[0]).toMatchObject({
      title: "정정",
      date: { start: "2026-11-04T19:00:00+09:00" },
      studyId: id,
    });
    await a.saveAdminStudyAttendance(id, e.id, ["p1"], "admin");
    expect((await getTable("activities"))[0].attendeeIds).toEqual(["p1"]);
    await a.cancelAdminStudySession(id, e.id, "admin");
    expect((await getTable("events"))[0].status).toBe("cancelled");
    await expect(
      a.updateAdminStudySession(id, e.id, { title: "부활" }, "admin"),
    ).rejects.toMatchObject({ code: "CONFLICT" });
    await expect(
      a.createAdminStudySession(id, date, "부활", "admin"),
    ).rejects.toMatchObject({ code: "CONFLICT" });
    expect((await getTable("studies")).find((s) => s.id === id)?.status).toBe(
      id === "s1" ? "finished" : "cancelled",
    );
    expect((await __auditRows()).map((r) => r.actor)).toEqual([
      "admin",
      "admin",
      "admin",
      "admin",
    ]);
  },
);
it("rejects non-admins at both service and DB flow boundaries", async () => {
  const a = await api();
  await expect(
    a.createAdminStudySession("s1", date, "", "org"),
  ).rejects.toMatchObject({ code: "FORBIDDEN" });
  await expect(
    rpc("flow_admin_study_session", {
      op: "cancel",
      studyId: "s1",
      eventId: "ghost",
      actorId: "org",
      auditId: "audit",
      auditAt: date,
    }),
  ).rejects.toThrow("FORBIDDEN");
  expect(await getTable("events")).toEqual([]);
});
it("rejects cross-study events and unknown attendance IDs without changing records", async () => {
  const a = await api();
  const e = await a.createAdminStudySession("s1", date, "", "admin");
  for (const op of [
    () => a.updateAdminStudySession("s2", e.id, { title: "wrong" }, "admin"),
    () => a.cancelAdminStudySession("s2", e.id, "admin"),
    () => a.saveAdminStudyAttendance("s2", e.id, [], "admin"),
  ])
    await expect(op()).rejects.toMatchObject({ code: "NOT_FOUND" });
  await expect(
    a.saveAdminStudyAttendance("s1", e.id, ["outsider"], "admin"),
  ).rejects.toMatchObject({ code: "VALIDATION_FAILED" });
  expect((await getTable("activities"))[0].attendeeIds).toEqual([]);
});
it("retains the organizer closed-study restriction", async () => {
  await expect(
    createStudySession(study("s1") as never, date, { autoGenerated: false }),
  ).rejects.toMatchObject({ code: "CONFLICT" });
});

it("repeated session creation is idempotent and retains walk-in attendance", async () => {
  const a = await api();
  const e = await a.createAdminStudySession("s1", date, "첫 회차", "admin");
  const again = await a.createAdminStudySession(
    "s1",
    date,
    "ignored retry",
    "admin",
  );
  expect(again.id).toBe(e.id);
  expect(await getTable("events")).toHaveLength(1);
  expect(await getTable("activities")).toHaveLength(1);
  expect(await __auditRows()).toHaveLength(1);
  const activities = await getTable("activities");
  await __putRawDoc("table", "activities", {
    schemaVersion: 1,
    rows: activities.map((row) => ({ ...row, attendeeIds: ["walkin", "org"] })),
  });
  await invalidateTable("activities");
  await a.saveAdminStudyAttendance("s1", e.id, ["p1"], "admin");
  expect([...(await getTable("activities"))[0].attendeeIds].sort()).toEqual([
    "p1",
    "walkin",
  ]);
  await a.cancelAdminStudySession("s1", e.id, "admin");
  await expect(
    a.saveAdminStudyAttendance("s1", e.id, [], "admin"),
  ).rejects.toMatchObject({ code: "CONFLICT" });
});
it("rejects invalid dates and missing targets", async () => {
  const a = await api();
  await expect(
    a.createAdminStudySession("s1", "2026-02-30T19:00:00+09:00", "", "admin"),
  ).rejects.toMatchObject({ code: "VALIDATION_FAILED" });
  await expect(
    a.createAdminStudySession("missing", date, "", "admin"),
  ).rejects.toMatchObject({ code: "NOT_FOUND" });
  await expect(
    a.cancelAdminStudySession("s1", "missing", "admin"),
  ).rejects.toMatchObject({ code: "NOT_FOUND" });
  expect(await __auditRows()).toHaveLength(0);
});
it("rejects a title beyond the existing session title contract", async () => {
  const a = await api();
  await expect(
    a.createAdminStudySession("s1", date, "가".repeat(121), "admin"),
  ).rejects.toMatchObject({ code: "VALIDATION_FAILED" });
  expect(await getTable("events")).toHaveLength(0);
});
